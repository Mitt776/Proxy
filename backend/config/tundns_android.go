package config

// tunDNSAddress — адрес DNS внутри туннеля, который Android объявляет системе
// через VpnService.Builder.addDnsServer (значение едет в конфиг полем
// `dns_address` tun-инбаунда, оттуда в tun.Options.DNSAddress и дальше в Kotlin).
//
// Без него VpnService не объявляет ни одного сервера, и Android оставляет
// приложениям резолвер нижней сети. Тогда на заблокированный домен приезжает
// подставной ответ — fake-ip домашнего роутера с собственным обходом или
// заглушка провайдера, — приложение отправляет этот адрес в туннель, а на ноде
// он не значит ничего. Симптом обманчивый: туннель жив, незаблокированные сайты
// открываются, а заблокированные рвутся мгновенно, хотя по настоящему IP тот же
// сайт через тот же туннель грузится нормально.
//
// Адрес обязан лежать в подсети туннеля (172.19.0.1/30 — свободен только .2):
// пакет к нему должен попасть в tun, где ядро перехватывает DNS и отвечает уже
// своим резолвером (DoH через прокси), а не резолвером сети.
const tunDNSAddress = "172.19.0.2"
