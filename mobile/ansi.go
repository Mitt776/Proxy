package mobile

// Без build-тега android намеренно: функция чистая, и так её видит `go test` на
// любой машине — а проверять разбор escape-последовательностей руками на
// телефоне никто не станет.

import "strings"

// stripANSI выкидывает из строки терминальные последовательности цвета.
//
// Ядро красит журнал всегда и платформенного писателя об этом не спрашивает: в
// форке вызов `platformWriter.DisableColors()` при сборке фабрики логов
// закомментирован (log/observable.go), а `log.disable_color` из конфига до
// платформенного форматтера не доходит вовсе. На Windows проблемы нет — там
// ядро пишет в трубу и отключает цвет само. Здесь же без чистки вкладка
// «Журнал» показывает «^[[36mINFO^[[0m» вместо строки.
func stripANSI(s string) string {
	if !strings.ContainsRune(s, 0x1b) {
		return s
	}
	var b strings.Builder
	b.Grow(len(s))
	for i := 0; i < len(s); i++ {
		if s[i] != 0x1b {
			b.WriteByte(s[i])
			continue
		}
		// Пропускаем ESC [ … m целиком. Незакрытую последовательность (такого
		// быть не должно, но строка приходит извне) дочитываем до конца строки —
		// показывать её пользователю всё равно нечем.
		j := i + 1
		if j < len(s) && s[j] == '[' {
			for j < len(s) && s[j] != 'm' {
				j++
			}
			i = j
		}
		// Одинокий ESC без «[» — выкидываем только его, следующий символ к
		// последовательности не относится.
	}
	return b.String()
}
